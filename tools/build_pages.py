# ---------------------------------------------------------------- write
def replace_block(text, name, new):
    pattern = re.compile(rf"<!-- {name}:START.*?<!-- {name}:END -->", re.S)
    if not pattern.search(text):
        return text
    return pattern.sub(lambda _: new, text)


def main():
    for x in exams:
        out = ROOT / "exams" / x["slug"] / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(exam_page(x), encoding="utf-8")
    (ROOT / "exams" / "index.html").write_text(exams_index(), encoding="utf-8")

    # Root-level pages: exam cards + footer
    for name in ("index.html", "careers.html", "privacy.html", "terms.html", "contact.html"):
        f = ROOT / name
        if not f.exists():
            continue
        t = f.read_text(encoding="utf-8")
        cards = "\n          ".join(exam_card(x, "") for x in exams)
        t = replace_block(t, "EXAM-CARDS", f"<!-- EXAM-CARDS:START (generated) -->\n          {cards}\n          <!-- EXAM-CARDS:END -->")
        t = replace_block(t, "FOOTER", footer(""))
        t = re.sub(r"\?v=\d+\"", f'?v={ASSET_V}"', t)
        f.write_text(t, encoding="utf-8")

    # Sitemap
    pages = ["", "exams/"] + [f"exams/{x['slug']}/" for x in exams] + ["careers.html", "contact.html", "privacy.html", "terms.html"]
    pri = {"": "1.0", "exams/": "0.8"}
    urls = "\n".join(
        f"  <url>\n    <loc>{SITE}/{u}</loc>\n    <lastmod>{TODAY}</lastmod>\n    <priority>{pri.get(u, '0.7' if u.startswith('exams/') else '0.3')}</priority>\n  </url>"
        for u in pages
    )
    (ROOT / "sitemap.xml").write_text(
        f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{urls}\n</urlset>\n',
        encoding="utf-8",
    )

    # Verified stats from the live syllabus
    sd = ROOT / "site-data.json"
    data = json.loads(sd.read_text(encoding="utf-8"))
    for s in data.get("stats", []):
        if s.get("key") == "exams":
            s["value"] = len(exams)
        if s.get("key") == "topics":
            s["value"] = sum(x["n_topics"] for x in exams)
    sd.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"Built {len(exams)} exam pages, exams index, sitemap ({len(pages)} URLs).")
    print("Topics:", sum(x["n_topics"] for x in exams))


if __name__ == "__main__":
    main()
